// Imagem padrão para exercícios sem imagem específica
export const DEFAULT_EXERCISE_IMAGE = "https://images.unsplash.com/photo-1517836357463-d25dfeac3438?w=400&h=533&fit=crop&q=80";

/**
 * Retorna a imagem nativa do exercício pelo nome.
 * Busca por correspondência exata primeiro, depois parcial.
 */
export function getExerciseImage(exerciseName) {
  if (!exerciseName) return DEFAULT_EXERCISE_IMAGE;

  // Busca exata
  if (EXERCISE_IMAGES[exerciseName]) {
    return EXERCISE_IMAGES[exerciseName];
  }

  // Busca parcial (case-insensitive)
  const lowerName = exerciseName.toLowerCase();
  for (const [key, url] of Object.entries(EXERCISE_IMAGES)) {
    if (lowerName.includes(key.toLowerCase()) || key.toLowerCase().includes(lowerName)) {
      return url;
    }
  }

  // Busca por palavras-chave
  if (lowerName.includes("agach")) return EXERCISE_IMAGES["Agachamento livre"];
  if (lowerName.includes("flexão") || lowerName.includes("flexao")) return EXERCISE_IMAGES["Flexão de braço"];
  if (lowerName.includes("prancha")) return EXERCISE_IMAGES["Prancha baixa"];
  if (lowerName.includes("abdom") || lowerName.includes("crunch")) return EXERCISE_IMAGES["Abdominal curto"];
  if (lowerName.includes("corrida") || lowerName.includes("corr")) return EXERCISE_IMAGES["Corrida curta"];
  if (lowerName.includes("passada") || lowerName.includes("lunge")) return EXERCISE_IMAGES["Passada à frente"];
  if (lowerName.includes("burpee")) return EXERCISE_IMAGES["Burpee"];
  if (lowerName.includes("ombro") || lowerName.includes("elevação")) return EXERCISE_IMAGES["Elevação lateral de ombro"];
  if (lowerName.includes("mobilidade") || lowerName.includes("alongamento")) return EXERCISE_IMAGES["Mobilidade"];

  return DEFAULT_EXERCISE_IMAGE;
}